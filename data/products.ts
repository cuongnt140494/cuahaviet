// Helper functions
export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category === category);
}

export function getProductsBySeries(series: string): Product[] {
  return products.filter((p) => p.series === series);
}

export function getFeaturedProducts(limit: number = 4): Product[] {
  const featured = [
    products.find((p) => p.id === "cb"),
    products.find((p) => p.id === "e50i"),
    products.find((p) => p.id === "s300"),
    products.find((p) => p.id === "ad9"),
  ].filter(Boolean) as Product[];
  return featured.slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const lowerQuery = query.toLowerCase();
  return products.filter(
    (product) =>
      product.name.toLowerCase().includes(lowerQuery) ||
      product.description.toLowerCase().includes(lowerQuery)
  );
}
